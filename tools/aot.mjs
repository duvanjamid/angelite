/**
 * AngeLite ahead-of-time template compiler.
 *
 * Compiles a template to a JS module so the app ships WITHOUT the in-browser template compiler or
 * expression parser (use the runtime-only build: `@duvanjamid/angelite/lite/runtime`).
 *
 *   node tools/aot.mjs counter.html counter.aot.js --components ui-button,ui-card
 *
 *   import aot from './counter.aot.js';
 *   component(Counter, { selector: 'app-counter', imports: [Button, Card], aot });
 *
 * Also usable as a library (`compileTemplate`) and as an esbuild plugin (`aotPlugin`).
 */

import { JSDOM } from 'jsdom';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { parse } from '../src/utils/expression.js';
import { templateToBlueprint } from '../src/lite/compiler.js';
import { pipes } from '../src/lite/runtime.js';
import '../src/lite/pipes.js';

class Src {
  constructor(code) { this.code = code; }
}
const J = JSON.stringify;

// expression emitter: every method returns a JS expression over the context `c`
const E = {
  lit: v => (v === undefined ? 'undefined' : J(v)),
  id: name => `p(c,${J(name)})`,
  arr: items => `[${items.join(',')}]`,
  mem: (o, k) => `p(${o},${k})`,
  callm: (o, k, args) => `M(${[o, k, ...args].join(',')})`,
  calli: (fn, args, self) => `F(${[fn, self ? 'c' : 'undefined', ...args].join(',')})`,
  un: (u, a) => `(${u}${a})`,
  bin: (op, l, r) => `(${l}${op}${r})`,
  cond: (q, a, b) => `(${q}?${a}:${b})`
};

const fn = body => `c=>${body}`;

// names a template may always use
const BUILTIN_NAMES = new Set(['$event', '$index', '$count', '$first', '$last', '$even', '$odd', '$el']);

const backend = (components, found) => ({
  parse: src => parse(src, { ...E, id: name => { found.ids.add(name); return E.id(name); } }),
  pipe: (h, name, args) => { found.pipes.add(name); return `P(${[J(name), h, ...args].join(',')})`; },
  check: tag => found.tags.add(tag),
  fn: h => new Src(fn(h)),
  interp: parts => new Src(`A.interp([${parts.map((x, i) => (i % 2 ? fn(x) : J(x))).join(',')}])`),
  stmts: hs => new Src(`A.stmts([${hs.map(fn).join(',')}])`),
  pick: tests => new Src(`A.pick([${tests.map(t => (t ? t.code : 'null')).join(',')}])`),
  modelGet: (h, label) => new Src(`A.modelGet(${fn(h)},${J(label)})`),
  modelRun: h => new Src(`A.modelRun(${fn(h)})`),
  comp: tag => new Src(`K[${J(tag)}]`),
  A: {
    text: new Src('A.text'), model: new Src('A.model'), state: new Src('A.state'),
    prop: n => new Src(`A.prop(${J(n)})`),
    attr: n => new Src(`A.attr(${J(n)})`),
    input: n => new Src(`A.input(${J(n)})`),
    inputAttr: n => new Src(`A.inputAttr(${J(n)})`)
  },
  has: tag => components.has(tag)
});

function htmlOf(fragment, doc) {
  const t = doc.createElement('template');
  t.content.appendChild(fragment.cloneNode(true));
  return t.innerHTML;
}

function serialize(v, doc) {
  if (v instanceof Src) return v.code;
  if (Array.isArray(v)) return `[${v.map(x => serialize(x, doc)).join(',')}]`;
  if (v && typeof v === 'object') {
    if (v.tpl) return `mk(${J(htmlOf(v.tpl, doc))},${serialize(v.ops, doc)},${serialize(v.upd, doc)},${!!v.dynamic})`;
    return `{${Object.entries(v).filter(([, x]) => x !== undefined)
      .map(([k, x]) => `${J(k)}:${serialize(x, doc)}`).join(',')}}`;
  }
  return v === undefined ? 'undefined' : J(v);
}

// @for variables declared anywhere in the blueprint tree
function loopVariables(bp, out = new Set()) {
  for (const op of bp.ops) {
    if (op.type === 'for') out.add(op.name);
    for (const sub of [op.bp, op.empty, op.placeholder, ...(op.branches || []).map(b => b.bp), ...Object.values(op.slots || {})]) {
      if (sub) loopVariables(sub, out);
    }
  }
  return out;
}

function build(source, { components = [], members, pipes: extraPipes = [], elements = [] }) {
  const dom = new JSDOM('<!doctype html><body></body>');
  const prev = globalThis.document;
  globalThis.document = dom.window.document;
  try {
    const tags = new Set(components.map(t => t.toLowerCase()));
    const found = { ids: new Set(), pipes: new Set(), tags: new Set() };
    const B = backend(tags, found);
    // `compile` only needs truthiness + the tag to build a reference
    const map = new Proxy({}, { get: (_, tag) => (tags.has(tag) ? true : undefined) });
    const bp = templateToBlueprint(source, map, B);
    const body = serialize(bp, dom.window.document);
    const code = `// Generated by angelite-aot - do not edit\nexport default (K, R) => {\n  const { A, P, p, M, F, mk } = R;\n  return ${body};\n};\n`;

    const diagnostics = [];
    const knownElements = new Set(elements.map(t => t.toLowerCase()));
    for (const tag of found.tags) {
      if (!tags.has(tag) && !knownElements.has(tag)) diagnostics.push(`unknown element <${tag}>: add it to "components" (or "elements" if it is a custom element)`);
    }
    const knownPipes = new Set([...Object.keys(pipes), ...extraPipes]);
    for (const name of found.pipes) if (!knownPipes.has(name)) diagnostics.push(`unknown pipe "${name}"`);
    if (members) {
      const allowed = new Set([...members, ...BUILTIN_NAMES, ...loopVariables(bp)]);
      for (const id of found.ids) if (!allowed.has(id)) diagnostics.push(`"${id}" is not a member of the component`);
    }
    return { code, diagnostics };
  } finally {
    globalThis.document = prev;
  }
}

/**
 * Checks a template without emitting code: unknown elements, unknown pipes and (when `members` lists the
 * component's fields and methods) names that the component does not have. Returns the list of problems.
 */
export function checkTemplate(source, options = {}) {
  return build(source, options).diagnostics;
}

/**
 * Compiles template source to the source of an ES module whose default export is the `aot` factory.
 * `components`: tag names (lowercase) that are components, e.g. ['ui-button'].
 * `check`: what to do with problems found by checkTemplate: 'warn' (default, console.warn), 'error' (throw) or false.
 * Also accepts `members`, `pipes` and `elements` (see checkTemplate).
 */
export function compileTemplate(source, options = {}) {
  const { code, diagnostics } = build(source, options);
  const mode = options.check === undefined ? 'warn' : options.check;
  if (diagnostics.length && mode) {
    const text = `angelite-aot: ${diagnostics.join('; ')}`;
    if (mode === 'error') throw new Error(text);
    console.warn(text);
  }
  return code;
}

/** Best-effort list of a component's fields and methods, read from the class source next to the template. */
export function discoverMembers(file) {
  const names = new Set();
  for (const ext of ['.js', '.mjs', '.ts']) {
    const sibling = file.replace(/\.ng\.html$/, ext);
    if (sibling === file || !existsSync(sibling)) continue;
    const src = readFileSync(sibling, 'utf8');
    for (const m of src.matchAll(/^\s*(?:static\s+)?(?:async\s+)?(?:get\s+|set\s+)?([A-Za-z_$][\w$]*)\s*(?:=|\(|;|:)/gm)) names.add(m[1]);
    for (const m of src.matchAll(/this\.([A-Za-z_$][\w$]*)\s*=/g)) names.add(m[1]);
    break;
  }
  return [...names];
}

/** esbuild plugin: `import aot from './app.ng.html'` yields the precompiled factory. */
export function aotPlugin({ components = [], members, check = 'warn', ...rest } = {}) {
  return {
    name: 'angelite-aot',
    setup(esbuild) {
      esbuild.onLoad({ filter: /\.ng\.html$/ }, args => {
        const source = readFileSync(args.path, 'utf8');
        // members: an array, or 'auto' to read them from the class file next to the template (best effort)
        const list = members === 'auto' ? discoverMembers(args.path) : members;
        const { code, diagnostics } = build(source, { components, members: list, ...rest });
        const messages = diagnostics.map(text => ({ text, location: { file: args.path } }));
        if (check === 'error' && messages.length) return { errors: messages };
        return { contents: code, loader: 'js', warnings: check ? messages : [] };
      });
    }
  };
}

// CLI: node tools/aot.mjs <template.html> <out.js> [--components a,b]
if (import.meta.url === `file://${process.argv[1]}`) {
  const [input, output, flag, list] = process.argv.slice(2);
  if (!input || !output) {
    console.error('usage: node tools/aot.mjs <template.html> <out.js> [--components ui-button,ui-card]');
    process.exit(1);
  }
  const components = flag === '--components' && list ? list.split(',') : [];
  writeFileSync(output, compileTemplate(readFileSync(input, 'utf8'), { components }));
  console.log(`compiled ${input} -> ${output}`);
}
